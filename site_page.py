#!/usr/bin/env python3
"""site_page — КООРДИНАТА СТРАНИЦЫ ВЕБ-ОРИДЖИНА: одна точка, три прочтения.

════════════════════════════════════════════════════════════════════════════════════════════
ЗАКОН
════════════════════════════════════════════════════════════════════════════════════════════

У страницы статического ориджина ОДНА координата и три её прочтения — имя, которым её
объявляет отношение Вещаний; адрес, которым её берёт читатель; файл, которым её несёт
сборка:

    Page  ≅  slug                       "" — корень ориджина (нейтраль, не особый случай)

    file    : Page → RelPath            slug/index.html   |   index.html
    url     : Page → Url                /slug/            |   /
    of_file : RelPath ⇀ Page            ЧАСТИЧНА

    of_file ∘ file = id_Page                       -- сечение (retraction)
    dom(of_file)   = im(file)                      -- ТОЧНОСТЬ, а не над-приближение

Вторая строка — та, ради которой модуль и писан. Пока у проекции нет обратной, мир
перечисляют глобом, а «наша ли это страница» спрашивают У САМОГО ФАЙЛА (`<meta
name="dela:slug">`, `broadcast_relation.world_orphans`). Метка есть ОБХОД отсутствующей
проекции, и она держится ровно до тех пор, пока функции «где ложится объявленная
единица» в Системе нет.

ЧЕМ ЗАКРЕПЛЁН ХВОСТОВОЙ СЛЭШ У `url` — и почему не сечением. Обратной у `url` здесь НЕТ, и
это следствие замера, а не пробел: потребителя «адрес ↦ единица» в Системе ноль (адреса
разрешает `site_closure`, и ему нужен носитель ЛЮБОГО адреса — `index_of`, — а не суждение
о том, что адрес есть страница). Сечение её и не закрепило бы: разбор адреса нормализует,
`/art` и `/art/` для него одно, поэтому `of_url ∘ url = id` истинно при ОБЕИХ раскладках —
положительный ответ, который никакой вход не отменяет. Закрепляет внешний авторитет:
RFC 3986 §5.2, разрешение относительной ссылки. Со страницы `/art` ссылка `styles.css`
разрешается против `/`, со страницы `/art/` — против `/art/`. Хвостовой слэш есть РАЗНИЦА
В МИРЕ, а не оформление; свидетелем стоит `urllib.parse.urljoin` — реализация того же RFC,
которую мы не писали.

════════════════════════════════════════════════════════════════════════════════════════════
КОРЕНЬ (замерено 2026-08-10 — AST по scripts/, не орфография)
════════════════════════════════════════════════════════════════════════════════════════════

Композиция координаты написана 25 раз в 10 модулях (тесты сверх того): site_generator (4
записи), broadcast_html (5 записей + 4 чтения), broadcast_relation, css_audit, site_closure,
site_preview, surface_compliance… Дома нет — значит каждый потребитель ВЫВОДИТ раскладку
заново, и расхождение между пересказами не то что не проверяется, а неформулируемо.

Оно и разошлось, ровно посередине:

    broadcast_html._emit_sitemap   tmp.rglob("index.html")                     -- глубина ∞
    css_audit.publish_gate         glob("index.html") + glob("*/index.html")   -- глубина 1

Два перечисления ОДНОГО множества, различающиеся на все страницы глубже первого этажа. Ни
одна из сторон заметить этого не могла: у каждой свой фолд, а `all(D_narrow) = ⊤` бит в бит
равен `all(D_true) = ⊤` (subsystem-publish-surface §THE PROPERTY IS THE TOTALITY OF THE
COMPOSITION — «инструмент для ЗНАЧЕНИЙ и ни одного для ОБЛАСТИ»). Здесь узость снята:
перечисление ОДНО и оно есть ПРООБРАЗ `of_file`, а не глоб со своей глубиной у каждого.

Spec: subsystem-publish-surface — S = (D, F, π). Этот модуль есть **F** для ноги, чей
носитель ИНДЕКСИРОВАН единицей (сайт, посадочная, превью, FUSE-зеркало ориджина): F там не
файл, а отображение «единица ↦ файл», и оно обязано иметь один дом — как D и π.

ОБЛАСТЬ ОБЪЯВЛЕНА И УЗКА НАМЕРЕННО: статический веб-ориджин, где каталог служится своим
индексом. Сообщение Телеграма или пост IG — тоже F, но с иной адресацией; расширить область
здесь значило бы объявить общность, которой не измерено (индексированный класс поверхностей
у Системы ровно один). Узость, КОТОРУЮ ВИДНО, — не дефект; дефект — узость, которую не видно.

Лист: только stdlib. Его импортируют генератор, обе ноги деплоя, превью, аудиты и пробы —
со всякой иной зависимостью он стал бы недостижим для части из них.
"""
from __future__ import annotations

from collections.abc import Iterable, Mapping
from dataclasses import dataclass
from pathlib import Path, PurePosixPath

#: Имя носителя каталога. Правило адресации ПЛАТФОРМЫ (каталог служится своим индексом),
#: а не наша вольность — потому и единственное написание на Систему.
INDEX = "index.html"

#: Приватный префикс сегмента: `_raw`, `_publications` — внутренние носители репозитория.
#: НЕ закон адресации (при `.nojekyll` они служатся), а объявление «миру не рекламируем»,
#: которым `_emit_sitemap` уже пользовался. Точка — иное: `.git` есть история, а не
#: содержание, и её отвергает сам `of_file` (см. `_addressable`).
PRIVATE_PREFIX = "_"


class NotAPageError(ValueError):
    """Битая ДЕКЛАРАЦИЯ единицы — ошибка конфигурации, а не наблюдение о мире.

    Полярности различены намеренно, и различие типовое: конструктор из декларации
    (`Page(...)`) РОНЯЕТ — сломанный slug есть конфиг-ошибка деплоя того же класса, что
    `BroadcastDeclarationError`; разбор мира (`of_file`) отдаёт `None` — «этот файл не несёт
    страницы» есть законный ФАКТ о мире, а не отказ инструмента."""


def _addressable(seg: str) -> bool:
    """Сегмент, который ориджин вообще способен служить: непуст, не «.»/«..», не dot-путь."""
    return bool(seg) and seg not in (".", "..") and not seg.startswith(".")


def index_of(rel: str) -> str:
    """Носитель адреса-каталога — строковое прочтение того же закона.

    Нужно там, где адрес ПРОИЗВОЛЕН и ещё неизвестно, страница ли это: `site_closure`
    разрешает всякий href (`styles.css`, `img/x.png`, `booking/`) и спрашивает «а будь это
    каталогом — чем бы он служился». Тот же закон, что `Page.file`, но без предварительного
    суждения о том, что адрес есть единица."""
    rel = str(rel).strip("/")
    return f"{rel}/{INDEX}" if rel else INDEX


@dataclass(frozen=True, order=True)
class Page:
    """Точка ориджина. `slug` — posix-путь сегментов; "" есть корень.

    Мультисегментность — не гипотеза на будущее: `_emit_sitemap` уже перечислял мир
    `rglob`-ом, то есть уже держал глубину ∞ своим доменом. Тип читается с мира, а не
    выбирается по вкусу."""

    slug: str = ""

    def __post_init__(self) -> None:
        raw = str(self.slug)
        if raw != raw.strip():
            raise NotAPageError(f"slug с краевыми пробелами: {raw!r}")
        norm = raw.strip("/")
        object.__setattr__(self, "slug", norm)
        if not norm:
            return                                  # корень — нейтраль, не особый случай
        for seg in norm.split("/"):
            if not _addressable(seg):
                raise NotAPageError(f"сегмент {seg!r} не адресуем ориджином: {raw!r}")
        if norm.rsplit("/", 1)[-1] == INDEX:
            raise NotAPageError(f"slug есть ИМЯ единицы, а не её носитель: {raw!r}")

    # ── прочтения координаты ────────────────────────────────────────────────────────────
    @property
    def segments(self) -> "tuple[str, ...]":
        return tuple(self.slug.split("/")) if self.slug else ()

    @property
    def file(self) -> PurePosixPath:
        """Файл-носитель ОТНОСИТЕЛЬНО корня сборки."""
        return PurePosixPath(index_of(self.slug))

    @property
    def url(self) -> str:
        """Адрес в ориджине — ровно та форма, что стоит в `<loc>` карты сайта.

        Хвостовой слэш — RFC 3986 §5.2, а не оформление: он есть база разрешения
        относительных ссылок этой страницы (см. §ЗАКОН)."""
        return f"/{self.slug}/" if self.slug else "/"

    @property
    def public(self) -> bool:
        """Рекламируется ли миру. `_`-сегмент — внутренний носитель репозитория."""
        return not any(s.startswith(PRIVATE_PREFIX) for s in self.segments)

    def at(self, root: "str | Path") -> Path:
        """Носитель под КОНКРЕТНЫМ корнем: клон сборки, каталог владельца, зеркало мира.

        Корень есть АРГУМЕНТ координаты, а не её часть — потому одна и та же страница
        адресуема во всех трёх мирах без второго написания раскладки."""
        return Path(root) / self.file

    # ── частичные обратные ──────────────────────────────────────────────────────────────
    @classmethod
    def of_file(cls, rel: "str | PurePosixPath | Path") -> "Page | None":
        """Файл ↦ единица, которую он несёт. `None` ⟺ файл не есть носитель страницы.

        Определена ТОЧНО на образе `file` — этим перечисление мира и становится честным:
        «страницы сборки» перестают быть глобом со своей глубиной у каждого читателя и
        становятся прообразом одной функции.

        ОБЛАСТЬ — путь ОТНОСИТЕЛЬНО корня ориджина, и абсолютный вход есть ⊥, а не тот же
        носитель. Ручная нормализация ведущего слэша была бы вторым выводом тождества пути
        (Π `path_repo_identity`: «один файл в двух написаниях получает два тождества, и
        лекарство принадлежит ОДНОЙ проекции»); здесь эта проекция — сам `of_file`, и она
        отвергает написание, которого её область не содержит."""
        p = PurePosixPath(str(rel))
        if p.name != INDEX:
            return None
        parts = tuple(s for s in p.parent.parts if s != ".")
        if not parts:
            return cls("")
        if not all(_addressable(s) for s in parts):
            return None
        return cls("/".join(parts))


def partition_by_page(locations: "Iterable[str]",
                      *, declared: "Mapping[str, Iterable[Page]] | None" = None,
                      ) -> "tuple[dict[Page, list[str]], list[str]]":
    """Раздел множества МЕСТ по координате единицы: `(размещённые, БЕЗ координаты)`.

    Прообраз `of_file`, взятый не по одному файлу, а по МНОЖЕСТВУ — та операция, которой
    пользуется всякий, кому нужно применить что-либо ПОСТРАНИЧНО к результату суждения,
    вынесенного о местах: удержать, переслать владельцу, показать.

    ВТОРОЙ ЧЛЕН — НЕ ОСТАТОК, А СОРТ. Место, у которого координаты нет (`"."`, имя закона,
    путь ИСТОЧНИКА вместо носителя сборки), не есть «страница, которую не нашли»: оно есть
    факт БЕЗ ЗЕРНА. Различие типовое, и потому потребитель не может о нём забыть — оно не
    прячется вторым значением в том же списке (тот самый дефект, который `publish_laws`
    снял у себя 2026-08-18: ⊥ закона лежал в списке нарушений, и сломанный СУДЬЯ обвинял
    ПОДСУДИМОГО). Что ⊥ координаты делает с АКТОМ, объявляет потребитель: у санкции это
    ⊤ — неразмещённый факт нельзя локализовать, значит он держит ВСЮ поверхность
    (Inv-EPI-unknown-is-identity в его точной форме для решётки координат: ⊥ есть единица
    ВСТРЕЧИ, а не элемент, который можно тихо отбросить).

    Пустое место (`""`) читается как ⊥, а не как корневая страница: `of_file` определена на
    ПУТЯХ, и пустой строки в её области нет — координата корня пишется `index.html`.

    ════════════════════════════════════════════════════════════════════════════════════════
    ВТОРОЕ ПРОЧТЕНИЕ МЕСТА — `declared`, И ОНО МНОЖЕСТВЕННО
    ════════════════════════════════════════════════════════════════════════════════════════

    `of_file` читает язык СБОРКИ (`slug/index.html`). Закон КЛАССА сущности говорит на языке
    ИСТОЧНИКА (`texts/<имя>.md`), и это не тот же язык: у источника нет носителя в сборке,
    пока отношение вещания не скажет, каким адресом он ложится. Значит второе прочтение есть
    ДАННЫЕ, которые подаёт держатель отношения (`site_generator.broadcast_assignments`), а не
    ещё один разбор строки здесь.

    ЗНАЧЕНИЕ — МНОЖЕСТВО, и это замер, а не запас на будущее: `texts/styles-vs-trends.md`
    ложится ДВУМЯ адресами (`styles-vs-trends` и `stili-vs-trendy` — алиас/редирект), как и
    конспект эфира. Одна сущность ⇒ слой над ней; зерно факта об источнике есть ВЕСЬ слой,
    иначе половина манифестаций уехала бы в мир с нарушением, о котором суждение уже вынесено.

        γ : Location ⇀ 𝒫(Page)      сборка ↦ {of_file}   ·   источник ↦ слой   ·   иначе ∅ ⇒ ⊤
    """
    located: "dict[Page, list[str]]" = {}
    loose: "list[str]" = []
    for loc in locations:
        pg = Page.of_file(loc) if loc else None
        fiber = [pg] if pg is not None else list((declared or {}).get(loc) or ())
        if not fiber:
            loose.append(loc)
        for member in fiber:
            located.setdefault(member, []).append(loc)
    return located, loose


def address_of(rel: "str | PurePosixPath | Path") -> str:
    """Носитель ↦ адрес, которым мир его берёт. ТОТАЛЬНА — и в этом весь смысл.

    Носители поверхности двух родов: индексируемые (каталог служится своим индексом) и
    ПЛОСКИЕ (`telegram.txt`, `bio.txt`, `robots.txt` — служатся собой). Соблазн — завести
    сумму типов; она не нужна: адрес есть ФУНКЦИЯ пути носителя, и всё различие двух родов
    несёт имя `index.html`, которое у модуля уже есть. Один закон, ни одной ветки у
    потребителя — превью и деплой ключуются одинаково для обоих родов.

    Обратной не объявляется: `index_of` отвечает на ДРУГОЙ вопрос («будь адрес каталогом»),
    и на плоском носителе быть ей обратной нечем. Две функции, два вопроса, без ложной
    двойственности.

    ОБЛАСТЬ — носитель ОТНОСИТЕЛЬНО корня ориджина (единственный источник — `Projection.file`)."""
    p = PurePosixPath(str(rel))
    page = Page.of_file(p)
    return page.url if page is not None else "/" + p.as_posix()


# ── МИР: перечисление страниц есть ПРООБРАЗ, а не глоб ──────────────────────────────────

def pages_under(root: "str | Path", *,
                public_only: bool = True) -> "list[tuple[Page, Path]]":
    """Страницы, которые НЕСЁТ дерево, — отсортированные, со своими носителями.

    ОДНО перечисление на Систему: клон деплоя, каталог владельца, зеркало мира. До этого
    их было два, разной глубины (см. §КОРЕНЬ), и разница была невидима обеим сторонам.
    Глубина здесь ∞ — адресуемость страницы от глубины не зависит.

    `public_only` — ОБЪЯВЛЕННЫЙ параметр, а не молчаливый фильтр: карта сайта рекламирует
    только публичные, аудит носителей вправе смотреть все."""
    root = Path(root)
    if not root.is_dir():
        return []
    out: "list[tuple[Page, Path]]" = []
    for carrier in root.rglob(INDEX):
        if not carrier.is_file():
            continue
        page = Page.of_file(carrier.relative_to(root).as_posix())
        if page is None or (public_only and not page.public):
            continue
        out.append((page, carrier))
    return sorted(out, key=lambda pc: pc[0].slug)


def slugs_under(root: "str | Path", *, public_only: bool = True) -> "set[str]":
    """Единицы, объявленные САМИМ миром (подкаталог со своим индексом).

    Корень ориджина в множество не входит: `""` есть проекция владельца, а не единица
    отношения, и множества различаются ровно на неё."""
    return {p.slug for p, _ in pages_under(root, public_only=public_only) if p.slug}
